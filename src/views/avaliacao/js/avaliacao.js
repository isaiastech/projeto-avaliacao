$(document).ready(function () {

    /*
    |--------------------------------------------------------------------------
    | CONFIGURAÇÕES
    |--------------------------------------------------------------------------
    */

    const form = $('#formAvaliacao');

    const etapas = $('.etapa');

    const totalEtapas = etapas.length;

    const totalAvaliacoes = $('.etapa-avaliacao').length;

    let etapaAtual = 0;


    /*
    |--------------------------------------------------------------------------
    | MÁSCARA DE TELEFONE
    |--------------------------------------------------------------------------
    */

    $('#fone').mask('(00) 00000-0000');


    /*
    |--------------------------------------------------------------------------
    | APARTAMENTO SOMENTE NÚMEROS
    |--------------------------------------------------------------------------
    */

    $('#apto').on('input', function () {

        this.value = this.value.replace(
            /[^0-9]/g,
            ''
        );

    });


    /*
    |--------------------------------------------------------------------------
    | NOME
    |--------------------------------------------------------------------------
    */

    $('#hospede').on('input', function () {

        this.value = this.value.replace(
            /[^a-zA-ZÀ-ÿ\s]/g,
            ''
        );

    });


    /*
    |--------------------------------------------------------------------------
    | MOSTRAR ETAPA
    |--------------------------------------------------------------------------
    */

    function mostrarEtapa(numero) {

        if (
            numero < 0 ||
            numero >= totalEtapas
        ) {

            return;

        }


        /*
        |--------------------------------------------------------------
        | REMOVE ETAPA ATUAL
        |--------------------------------------------------------------
        */

        etapas.removeClass('ativa');


        /*
        |--------------------------------------------------------------
        | MOSTRA NOVA ETAPA
        |--------------------------------------------------------------
        */

        const etapa = etapas.eq(numero);

        etapa.addClass('ativa');


        /*
        |--------------------------------------------------------------
        | ATUALIZA ETAPA
        |--------------------------------------------------------------
        */

        etapaAtual = numero;


        /*
        |--------------------------------------------------------------
        | ATUALIZA PROGRESSO
        |--------------------------------------------------------------
        */

        atualizarProgresso();


        /*
        |--------------------------------------------------------------
        | VOLTA PARA O TOPO
        |--------------------------------------------------------------
        */

        window.scrollTo({

            top: 0,

            behavior: 'smooth'

        });

    }


    /*
    |--------------------------------------------------------------------------
    | ATUALIZAR PROGRESSO
    |--------------------------------------------------------------------------
    */

    function atualizarProgresso() {

        const etapa =
            etapas.eq(etapaAtual);


        const titulo =
            etapa.data('titulo') || 'Avaliação';


        /*
        |--------------------------------------------------------------
        | TÍTULO
        |--------------------------------------------------------------
        */

        $('#etapaTitulo').text(
            titulo
        );


        /*
        |--------------------------------------------------------------
        | PROGRESSO
        |--------------------------------------------------------------
        */

        const progresso =
            ((etapaAtual + 1) / totalEtapas) * 100;


        $('#barraProgresso').css(
            'width',
            progresso + '%'
        );


        /*
        |--------------------------------------------------------------
        | CONTADOR
        |--------------------------------------------------------------
        */

        if (
            etapaAtual === 0
        ) {

            $('#contadorEtapa').text(
                'Dados pessoais'
            );

        } else if (
            etapaAtual <= totalAvaliacoes
        ) {

            $('#contadorEtapa').text(
                etapaAtual +
                ' de ' +
                totalAvaliacoes
            );

        } else {

            $('#contadorEtapa').text(
                'Última etapa'
            );

        }

    }


    /*
    |--------------------------------------------------------------------------
    | VALIDAR DADOS DO HÓSPEDE
    |--------------------------------------------------------------------------
    */

    function validarDados() {

        let valido = true;


        /*
        |--------------------------------------------------------------
        | NOME
        |--------------------------------------------------------------
        */

        const hospede =
            $('#hospede')
                .val()
                .trim();


        if (
            hospede === ''
        ) {

            $('#hospede')
                .addClass('is-invalid')
                .removeClass('is-valid')
                .focus();

            valido = false;

        } else {

            $('#hospede')
                .removeClass('is-invalid')
                .addClass('is-valid');

        }


        /*
        |--------------------------------------------------------------
        | APARTAMENTO
        |--------------------------------------------------------------
        */

        const apto =
            $('#apto')
                .val()
                .trim();


        if (
            apto === '' ||
            !/^[0-9]+$/.test(apto)
        ) {

            $('#apto')
                .addClass('is-invalid')
                .removeClass('is-valid')
                .focus();

            valido = false;

        } else {

            $('#apto')
                .removeClass('is-invalid')
                .addClass('is-valid');

        }


        /*
        |--------------------------------------------------------------
        | EMAIL
        |--------------------------------------------------------------
        */

        const email =
            $('#email')
                .val()
                .trim();


        if (
            email !== '' &&
            !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)
        ) {

            $('#email')
                .addClass('is-invalid')
                .removeClass('is-valid')
                .focus();

            valido = false;

        } else {

            $('#email')
                .removeClass('is-invalid');

        }


        /*
        |--------------------------------------------------------------
        | DATA
        |--------------------------------------------------------------
        */

        const data =
            $('#data_avaliacao')
                .val()
                .trim();


        if (
            data === ''
        ) {

            $('#data_avaliacao')
                .addClass('is-invalid')
                .removeClass('is-valid');

            valido = false;

        } else {

            $('#data_avaliacao')
                .removeClass('is-invalid')
                .addClass('is-valid');

        }


        return valido;

    }


    /*
    |--------------------------------------------------------------------------
    | BOTÃO "COMEÇAR AVALIAÇÃO"
    |--------------------------------------------------------------------------
    */

    $('.btn-iniciar').on(
        'click',
        function () {

            /*
            |----------------------------------------------------------
            | VALIDA DADOS
            |----------------------------------------------------------
            */

            if (
                !validarDados()
            ) {

                return;

            }


            /*
            |----------------------------------------------------------
            | VAI PARA PRIMEIRA AVALIAÇÃO
            |----------------------------------------------------------
            */

            mostrarEtapa(1);

        }
    );


    /*
    |--------------------------------------------------------------------------
    | BOTÃO "PRÓXIMO"
    |--------------------------------------------------------------------------
    */

    $('.btn-proximo').on(
        'click',
        function () {

            const etapa =
                etapas.eq(etapaAtual);


            const radio =
                etapa.find(
                    'input[type="radio"]'
                );


            /*
            |----------------------------------------------------------
            | VERIFICA SE RESPONDEU
            |----------------------------------------------------------
            */

            if (
                radio.length > 0 &&
                !radio.is(':checked')
            ) {

                return;

            }


            /*
            |----------------------------------------------------------
            | AVANÇA
            |----------------------------------------------------------
            */

            mostrarEtapa(
                etapaAtual + 1
            );

        }
    );


    /*
    |--------------------------------------------------------------------------
    | BOTÃO "ANTERIOR"
    |--------------------------------------------------------------------------
    */

    $('.btn-anterior').on(
        'click',
        function () {

            mostrarEtapa(
                etapaAtual - 1
            );

        }
    );


    /*
    |--------------------------------------------------------------------------
    | SELEÇÃO DAS OPÇÕES
    |--------------------------------------------------------------------------
    */

    $('.opcao-avaliacao input').on(
        'change',
        function () {

            const etapa =
                $(this).closest('.etapa');


            /*
            |----------------------------------------------------------
            | REMOVE SELEÇÃO ANTERIOR
            |----------------------------------------------------------
            */

            etapa
                .find('.opcao-avaliacao')
                .removeClass(
                    'selecionada'
                );


            /*
            |----------------------------------------------------------
            | MARCA OPÇÃO SELECIONADA
            |----------------------------------------------------------
            */

            $(this)
                .closest('.opcao-avaliacao')
                .addClass(
                    'selecionada'
                );


            /*
            |----------------------------------------------------------
            | HABILITA BOTÃO
            |----------------------------------------------------------
            */

            etapa
                .find('.btn-proximo')
                .prop(
                    'disabled',
                    false
                );


            /*
            |----------------------------------------------------------
            | AVANÇA AUTOMATICAMENTE
            |----------------------------------------------------------
            */

            setTimeout(
                function () {

                    mostrarEtapa(
                        etapaAtual + 1
                    );

                },
                300
            );

        }
    );


    /*
    |--------------------------------------------------------------------------
    | CONTADOR DE CARACTERES
    |--------------------------------------------------------------------------
    */

    $('#sugestoes').on(
        'input',
        function () {

            $('#contadorCaracteres').text(
                this.value.length
            );

        }
    );


    /*
    |--------------------------------------------------------------------------
    | ENVIO DO FORMULÁRIO
    |--------------------------------------------------------------------------
    */

    form.on(
        'submit',
        function () {

            /*
            |----------------------------------------------------------
            | DESABILITA BOTÃO
            |----------------------------------------------------------
            */

            $('#btnEnviar').prop(
                'disabled',
                true
            );


            /*
            |----------------------------------------------------------
            | MOSTRA LOADING
            |----------------------------------------------------------
            */

            $('.texto-enviar').hide();

            $('.texto-loading').show();


            /*
            |----------------------------------------------------------
            | DEIXA FORMULÁRIO SER ENVIADO
            |----------------------------------------------------------
            */

            return true;

        }
    );


    /*
    |--------------------------------------------------------------------------
    | REMOVE ERRO AO DIGITAR
    |--------------------------------------------------------------------------
    */

    $('input, textarea').on(
        'input change',
        function () {

            $(this)
                .removeClass(
                    'is-invalid'
                );

        }
    );


    /*
    |--------------------------------------------------------------------------
    | INICIALIZAÇÃO
    |--------------------------------------------------------------------------
    */

    mostrarEtapa(0);

});